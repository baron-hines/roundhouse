#!/usr/bin/env ruby
# frozen_string_literal: true

# Writes an RBS sidecar for discourse's SiteSetting readers from
# config/site_settings.yml, for roundhouse to read from the app's sig/.
#
#   ruby tools/discourse/site_settings_rbs.rb DISCOURSE_ROOT > DISCOURSE_ROOT/sig/site_setting.rbs
#
# SiteSettingExtension#setup_methods defines these methods at boot, so the
# Ruby family runs them; the sidecar only types them. A reader's type is the
# value TypeSupervisor#to_rb_value answers for the setting's type (its
# `type:`, or its default's class). A setting whose reader can answer
# something else is left out and stays untyped.

require "yaml"

root = ARGV.fetch(0) { abort "usage: #{$PROGRAM_NAME} DISCOURSE_ROOT" }
yaml = YAML.load_file(File.join(root, "config/site_settings.yml"), aliases: true)

# TypeSupervisor.types: a static `type:` outside it falls back to the default's class.
KNOWN = %w[
  string time integer float bool null enum list url_list host_list category_list value_list regex email username
  category uploaded_image_list upload group group_list tag_list color simple_list emoji_list html_deprecated
  tag_group_list file_size_restriction objects locale_enum
].freeze
# TypeSupervisor#to_rb_value's arms; the other known types answer the stored value, a String in the database.
CAST = { "float" => "Float", "integer" => "Integer", "file_size_restriction" => "Integer", "bool" => "bool",
         "string" => "String", "datetime" => "String", "icon" => "String", "date" => "String" }.freeze
LISTS = %w[list emoji_list tag_list host_list].freeze

def default_type(value)
  case value
  when String then "string"
  when Integer then "integer"
  when Float then "float"
  when true, false then "bool"
  end
end

out = ["# Generated by roundhouse's tools/discourse/site_settings_rbs.rb from config/site_settings.yml.", "class SiteSetting"]
yaml.each_value do |settings|
  settings.each do |name, spec|
    opts = spec.is_a?(Hash) ? spec : { "default" => spec }
    default = opts["default"]
    static = opts["type"]&.to_s
    static = "enum" if static.nil? && opts["enum"]
    type = static && KNOWN.include?(static) ? static : default_type(default)
    next if type.nil?
    clean = name.to_s.delete("?")
    # Not typed: an upcoming change answers UpcomingChanges.enabled?, a mandatory list a joined String, an enum
    # class with `wrap` its wrapped value, an upload a record and an object setting its parsed JSON.
    reader =
      if opts["upcoming_change"]
        "bool"
      elsif opts["mandatory_values"]
        "String"
      elsif type == "enum"
        opts["enum"] ? nil : (default.is_a?(Integer) ? "Integer" : "String")
      elsif %w[upload uploaded_image_list objects null].include?(type)
        nil
      else
        CAST.fetch(type, default.is_a?(String) ? "String" : nil)
      end
    next if reader.nil?
    out << "  def self.#{clean}: (?untyped scoped_to) -> #{reader}"
    out << "  def self.#{clean}?: (?untyped scoped_to) -> #{reader}"
    case type
    when "category_list", "group_list"
      out << "  def self.#{clean}_map: () -> Array[Integer]"
    when *LISTS
      list_type = opts["list_type"]&.to_s
      out << "  def self.#{clean}_map: (?untyped scoped_to) -> Array[String]" if list_type.nil? || %w[simple compact locale].include?(list_type)
    end
  end
end
out << "end"
puts out.join("\n")
