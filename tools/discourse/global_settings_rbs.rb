#!/usr/bin/env ruby
# frozen_string_literal: true

# Writes an RBS sidecar for discourse's GlobalSetting readers from
# config/discourse_defaults.conf and the app's `GlobalSetting.add_default`
# calls, for roundhouse to read from the app's sig/.
#
#   ruby tools/discourse/global_settings_rbs.rb DISCOURSE_ROOT > DISCOURSE_ROOT/sig/global_setting.rbs
#
# GlobalSetting.load_defaults defines these methods at boot, so the Ruby
# family runs them; the sidecar only declares them. A reader answers what
# BaseProvider.coerce makes of the value discourse.conf or a DISCOURSE_*
# variable gives it, which can be a String, an Integer, true, false or nil
# whatever the default is, so every reader is untyped.

root = ARGV.fetch(0) { abort "usage: #{$PROGRAM_NAME} DISCOURSE_ROOT" }

# FileProvider#read's pattern, so the keys are the ones it defines.
keys = File.read(File.join(root, "config/discourse_defaults.conf")).split("\n").filter_map do |line|
  line[/\A\s*([a-z_]+[a-z0-9_]*)\s*=/, 1]
end
Dir.glob(File.join(root, "{app,lib,config,plugins}/**/*.rb")).sort.each do |file|
  File.read(file).scan(/GlobalSetting\.add_default[ (]\s*(?::"?|")([a-z_][a-z0-9_]*)/) { keys << Regexp.last_match(1) }
end

out = ["# Generated by roundhouse's tools/discourse/global_settings_rbs.rb from config/discourse_defaults.conf.", "class GlobalSetting"]
keys.uniq.sort.each { |key| out << "  def self.#{key}: () -> untyped" }
out << "end"
puts out.join("\n")
